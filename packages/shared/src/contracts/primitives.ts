import { z } from 'zod';

/**
 * The small shapes every other contract is built from.
 *
 * Everything here is a zod schema with its TypeScript type derived by `z.infer`.
 * Never a hand-written interface beside a schema: the two drift, and the one
 * that drifts is always the one that is not validated.
 */

/** A cuid, which is what every `@id @default(cuid())` in the schema produces. */
export const idSchema = z
  .string()
  .min(20)
  .max(40)
  .regex(/^[a-z0-9]+$/u);

export const emailSchema = z.string().trim().toLowerCase().email().max(254);

export const nameSchema = z.string().trim().min(1).max(80);

/**
 * At least 12 characters. Not a composition rule -- no "one digit, one symbol" --
 * because those push people towards `Password1!` and measurably lower entropy.
 * Length is the property that matters.
 */
export const passwordSchema = z.string().min(12).max(200);

/**
 * A response id. Generated by the RESPONDENT'S browser, which is what makes a
 * retried save idempotent: the same id twice is the same row, by primary key.
 * A v4 UUID has 122 random bits, so guessing somebody else's in-progress
 * response is not a practical attack.
 */
export const responseIdSchema = z
  .string()
  .regex(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/u, 'a v4 UUID');

/**
 * A public form slug: what `/f/<slug>` carries. Lowercase so a link read aloud
 * or retyped still works.
 */
export const slugSchema = z.string().regex(/^[a-z0-9][a-z0-9-]{3,39}$/u);

/** A published version number. 1-based, gapless per form. */
export const versionNumberSchema = z.number().int().positive();

/** An ISO 8601 instant. Always UTC on the wire; rendering picks a zone. */
export const instantSchema = z.string().datetime();

export type Id = z.infer<typeof idSchema>;
export type ResponseId = z.infer<typeof responseIdSchema>;
